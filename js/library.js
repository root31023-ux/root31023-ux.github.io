const subjectButtons = [...document.querySelectorAll(".subject-btn")];
const workspaceEl = document.getElementById("subjectWorkspace");

function renderSubject(key) {
  const data = LIBRARY_DATA[key] || LIBRARY_DATA.basics;

  subjectButtons.forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.subject === key);
  });

  const chaptersHtml = data.chapters
    .map((ch) => {
      if (ch.locked) {
        return `
          <article class="chapter-box is-locked">
            <div class="chapter-head">
              <span class="chapter-code">${ch.code}</span>
              <span class="chapter-badge">${ch.badge}</span>
            </div>
            <h4 class="chapter-title">${ch.title}</h4>
            <div class="locked-msg">${ch.lockedText || "الملفات غير متوفرة حالياً"}</div>
          </article>
        `;
      }

      const linksHtml = ch.links
        .map((lnk) => {
          const targetAttr = lnk.sameTab ? "" : 'target="_blank" rel="noopener noreferrer"';
          return `
            <a href="${lnk.url}" ${targetAttr} class="doc-link">
              <span>${lnk.label}</span>
              <span>↗</span>
            </a>
          `;
        })
        .join("");

      return `
        <article class="chapter-box">
          <div class="chapter-head">
            <span class="chapter-code">${ch.code}</span>
            <span class="chapter-badge">${ch.badge}</span>
          </div>
          <h4 class="chapter-title">${ch.title}</h4>
          <div class="chapter-links">${linksHtml}</div>
        </article>
      `;
    })
    .join("");

  workspaceEl.innerHTML = `
    <div class="workspace-top">
      <div>
        <span class="sub-code">${data.code}</span>
        <h3>${data.title}</h3>
      </div>
      <span class="workspace-note">${data.note}</span>
    </div>
    <div class="chapters-grid">${chaptersHtml}</div>
  `;
}

subjectButtons.forEach((btn) => {
  btn.addEventListener("click", () => {
    renderSubject(btn.dataset.subject);
  });
});

renderSubject("basics");